def money(base, mult):
    """算出以 8 结尾的整数价格。"""
    v = int(round(base * mult / 10.0)) * 10
    return v - 2 if v % 10 == 0 else v


def build_shop(idx, row):
    (slug, name, city, district, distance, price, score,
     review_count, tags, intro, featured, art) = row

    rng = random.Random(slug)

    # --- 设施：按标签取 3 项 + 通用项补齐到 8 项 ---
    facs = []
    for t in tags:
        pool = FACILITY_POOL.get(t, [])
        if pool:
            facs.append(rng.choice(pool))
    for c in FACILITY_COMMON:
        if len(facs) >= 8:
            break
        facs.append(c)
    facs = list(dict.fromkeys(facs))[:8]

    # --- 房型：2~3 个，价格随人均价浮动 ---
    n_room = 3 if price >= 150 else 2
    picked = rng.sample(ROOM_POOL, n_room)
    picked.sort(key=lambda r: r[3])
    rooms = []
    for rname, bed, area, mult in picked:
        rooms.append({
            "name": rname,
            "bed": bed,
            "area": f"{area}㎡",
            "price": money(price, mult),
            "note": rng.choice(["含双早", "含双早 + 一顿农家菜", "含早餐与下午茶"]),
        })

    # --- 评价：3 条 ---
    tpls = rng.sample(REVIEW_TEMPLATES, 3)
    users = rng.sample(REVIEW_USERS, 3)
    seen = set()
    reviews = []
    base_date = date(2026, 6, 1)
    for i, ((text, sc), u) in enumerate(zip(tpls, users)):
        if u in seen:
            continue
        seen.add(u)
        d = base_date + timedelta(days=rng.randint(0, 100))
        reviews.append({
            "user": u,
            "from": rng.choice(REVIEW_FROMS),
            "score": sc,
            "date": d.isoformat(),
            # 三条评价轮换提及不同标签，避免整页反复出现同一个词
            "text": text.replace("{t1}", ACT_WORD.get(tags[i % len(tags)], tags[i % len(tags)])),
        })
    reviews.sort(key=lambda r: r["date"], reverse=True)

    return {
        "slug": slug,
        "name": name,
        "city": city,
        "district": district,
        "distance": distance,
        "price": price,
        "score": score,
        "reviewCount": review_count,
        "tags": tags,
        "phone": PHONE,
        "intro": intro,
        "featured": featured,
        "art": art,
        "facilities": facs,
        "rooms": rooms,
        "reviews": reviews,
    }


def main():
    shops = [build_shop(i, row) for i, row in enumerate(SHOPS)]
    out = ROOT / "data" / "shops.json"
    out.write_text(
        json.dumps(shops, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"已生成 {len(shops)} 家商家 -> {out}")
    print(f"城市分布: ", end="")
    from collections import Counter
    c = Counter(s["city"] for s in shops)
    print("、".join(f"{k} {v} 家" for k, v in c.items()))
    print(f"总评价数: {sum(s['reviewCount'] for s in shops):,}")


if __name__ == "__main__":
    main()
